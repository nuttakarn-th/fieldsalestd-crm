// ─── SVG DNA Strand ───────────────────────────────────────────────────────────
function dnaSVG(top5Themes: Theme[], allHighlight?: boolean): string {
  const totalSegments = 34;
  const svgW = 680;
  const svgH = 60;
  const leftArrowW = 40;
  const rightArrowW = 40;
  const usableW = svgW - leftArrowW - rightArrowW;
  const segW = usableW / totalSegments;
  const segGap = 1;
  const topDomains = top5Themes.map(t => t.domain);

  // Build segments
  let segs = "";
  for (let i = 0; i < totalSegments; i++) {
    const x = leftArrowW + i * segW + segGap / 2;
    const w = segW - segGap;
    // First 5 segments get domain colors (index = rank order)
    const color = i < 5 ? GALLUP_COLORS[top5Themes[i].domain].hex : "#D1D5DB";
    const h = i < 5 ? 40 : 28;
    const y = (svgH - h) / 2;
    const r = 2;
    segs += `<rect x="${x.toFixed(1)}" y="${y}" width="${w.toFixed(1)}" height="${h}" rx="${r}" fill="${color}" opacity="${i < 5 ? '1' : '0.6'}"/>`;
  }

  // Left arrow (chevron)
  const lp = `0,${svgH / 2} ${leftArrowW},10 ${leftArrowW},${svgH - 10}`;
  // Right arrow
  const rx0 = svgW - rightArrowW;
  const rp = `${rx0},10 ${svgW},${svgH / 2} ${rx0},${svgH - 10}`;

  return `<svg width="${svgW}" height="${svgH}" viewBox="0 0 ${svgW} ${svgH}" xmlns="http://www.w3.org/2000/svg" style="display:block;max-width:100%">
  <polygon points="${lp}" fill="#D1D5DB"/>
  ${segs}
  <polygon points="${rp}" fill="#D1D5DB"/>
</svg>`;
}

// ─── Helper: format date ──────────────────────────────────────────────────────
function todayTH(): string {
  const d = new Date();
  return `${String(d.getDate()).padStart(2, "0")}-${String(d.getMonth() + 1).padStart(2, "0")}-${d.getFullYear()}`;
}

